/** Widens literal `as const` leaves so other locales may use different strings. */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer Item)[]
        ? readonly Widen<Item>[]
        : { -readonly [Key in keyof T]: Widen<T[Key]> };

