/** Enum-keyed sections must stay exhaustive; usage sites index them by these unions. */
type ExhaustiveCopyKeys = {
  nav: Record<AppNavKey, string>;
  navGroups: Record<AppNavGroupKey, string>;
  status: Record<PipelineStepState, string>;
  overview: { continuation: Record<OverviewContinuationKind, string>; journey: { steps: Record<PipelineStepKey, string> } };
  chunking: { strategies: Record<ChunkStrategy, string>; strategyNotes: Record<ChunkStrategy, string> };
};

export const UI_COPY: Record<AppLocale, AppCopy> = { en, tr } satisfies Record<AppLocale, ExhaustiveCopyKeys>;

/** Copy for the active interface locale (PreferencesProvider owns the locale). */
export function useCopy(): AppCopy {
  const { preferences } = usePreferences();
  return UI_COPY[preferences.locale];
}

/** Fills `{name}` placeholders in a copy template; unknown placeholders stay visible. */
export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

/** "Parse #3" / "Ayrıştırma #3": one naming rule for every run list and band. */
export function runName(copy: AppCopy, kind: keyof AppCopy["runs"]["names"], runNumber: number | null | undefined): string {
  return `${copy.runs.names[kind]} #${runNumber ?? "—"}`;
}
